"""Frozen labelled corpora for the first RetryWise diagnosis model.

Training and held-out examples are intentionally separate constants. They are
small, synthetic, reviewable, and contain only values admitted by the redacted
feature schema. They are not represented as executable rules.
"""

from __future__ import annotations

from dataclasses import dataclass

from .schema import FeatureVector, normalize_features
from .taxonomy import FailureClass


@dataclass(frozen=True, slots=True)
class LabelledExample:
    label: FailureClass
    features: FeatureVector


def _row(
    label: FailureClass,
    payment_method: str,
    error_source: str,
    error_step: str,
    error_reason: str,
    incident_state: str,
    attempt_bucket: str,
    failure_age_bucket: str,
) -> LabelledExample:
    return LabelledExample(
        label=label,
        features=normalize_features(
            {
                "payment_method": payment_method,
                "error_source": error_source,
                "error_step": error_step,
                "error_reason": error_reason,
                "incident_state": incident_state,
                "attempt_bucket": attempt_bucket,
                "failure_age_bucket": failure_age_bucket,
            }
        ),
    )


